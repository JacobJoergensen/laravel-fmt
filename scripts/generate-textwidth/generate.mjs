// Generated, not hand-written: a hand-written block list missed 8,803 Wide
// characters (the transport-and-map emoji among them), so lines measured
// narrower than they paint and overflowed printWidth.
//
// Writes the output directly in UTF-8 rather than via stdout + shell
// redirection: PowerShell's default UTF-16 LE would otherwise produce output
// Go's parser rejects with `illegal UTF-8 encoding`.

import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { eastAsianWidthType } from 'get-east-asian-width'

const here = dirname(fileURLToPath(import.meta.url))

const outputPath = resolve(
  here,
  '..',
  '..',
  'internal',
  'textwidth',
  'wideranges_generated.go',
)

// Surrogates have no width of their own, so they are skipped and never reach
// the ranges.
const MAX = 0x10ffff
const SURROGATE_LO = 0xd800
const SURROGATE_HI = 0xdfff

function isWide(cp) {
  if (cp >= SURROGATE_LO && cp <= SURROGATE_HI) {
    return false
  }

  const type = eastAsianWidthType(cp)

  return type === 'wide' || type === 'fullwidth'
}

function collectRanges() {
  const ranges = []
  let start = -1

  for (let cp = 0; cp <= MAX; cp++) {
    if (isWide(cp)) {
      if (start < 0) {
        start = cp
      }

      continue
    }

    if (start >= 0) {
      ranges.push([start, cp - 1])
      start = -1
    }
  }

  if (start >= 0) {
    ranges.push([start, MAX])
  }

  return ranges
}

function hex(cp) {
  return '0x' + cp.toString(16).toUpperCase()
}

function render(ranges) {
  const covered = ranges.reduce((n, [lo, hi]) => n + (hi - lo + 1), 0)

  const lines = [
    '// Code generated by scripts/generate-textwidth. DO NOT EDIT.',
    '',
    'package textwidth',
    '',
    '// wideRanges holds every East Asian Wide and Fullwidth range, ascending and',
    '// non-adjacent, straight from the Unicode East_Asian_Width property. Rune',
    `// binary-searches it. ${ranges.length} ranges cover ${covered} code points.`,
    'var wideRanges = [...][2]rune{',
  ]

  for (const [lo, hi] of ranges) {
    lines.push(`\t{${hex(lo)}, ${hex(hi)}},`)
  }

  lines.push('}')

  return lines.join('\n') + '\n'
}

const ranges = collectRanges()
writeFileSync(outputPath, render(ranges), 'utf8')
execFileSync('gofmt', ['-w', outputPath], { stdio: 'inherit' })

console.log(`wrote ${ranges.length} ranges to ${outputPath}`)
